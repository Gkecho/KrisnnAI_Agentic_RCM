"""Generate the SQL Server schema (tables, keys, foreign keys, column descriptions) and Mermaid ER diagrams from build/model.json.

Outputs (default docs/data_model/): schema_sqlserver.sql and ER-diagrams.md.
Override with KRISNNAI_SQL_OUT and KRISNNAI_ER_OUT.
Foreign keys are created only when the child column and the parent key have the same type; the rest are listed in the report at the end of the SQL file.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.normpath(os.path.join(HERE, "..", "..", "docs", "data_model"))
SQL_OUT = os.environ.get("KRISNNAI_SQL_OUT") or os.path.join(DOCS, "schema_sqlserver.sql")
ER_OUT = os.environ.get("KRISNNAI_ER_OUT") or os.path.join(DOCS, "ER-diagrams.md")
M = json.load(open(os.path.join(HERE, "build", "model.json"), encoding="utf-8"))
T = {t["name"]: t for t in M["tables"]}


def q(name):
    return "[" + name + "]"


def lit(s):
    return "N'" + str(s).replace("'", "''") + "'"


def pk_col(table):
    return T[table]["cols"][0]["name"]      # the first column is always the internal identity ID


def pk_type(table):
    return T[table]["cols"][0]["type"]


out = ["-- KrisnnAI canonical data model: SQL Server schema. GENERATED by tools/data_model/build_sql.py, do not edit by hand.",
       f"-- {len(T)} tables, {sum(len(t['cols']) for t in T.values())} columns. Synthetic data only; no real PHI.",
       "-- Mandatory columns are NOT NULL; Important and Optional are nullable (each has a documented fallback).",
       "-- Every table and column carries its description as an extended property (MS_Description).", "",
       "SET NOCOUNT ON;", "GO"]
fks, skipped = [], []
for t in M["tables"]:
    n = t["name"]
    lines = []
    for c in t["cols"]:
        ident = " IDENTITY(1,1)" if c["name"] == pk_col(n) else ""
        null = "NOT NULL" if (c["priority"] == "Mandatory" or c["name"] == pk_col(n)) else "NULL"
        lines.append(f"    {q(c['name'])} {c['type']}{ident} {null}")
        if c.get("link"):
            if c["link"] not in T:
                skipped.append((n, c["name"], c["link"], "unknown table"))
            elif pk_type(c["link"]) != c["type"]:
                skipped.append((n, c["name"], c["link"], f"{c['type']} vs {pk_type(c['link'])}"))
            else:
                fks.append((n, c["name"], c["link"]))
    lines.append(f"    CONSTRAINT {q('PK_' + n)} PRIMARY KEY CLUSTERED ({q(pk_col(n))})")
    out += [f"CREATE TABLE [dbo].{q(n)} (", ",\n".join(lines), ");", "GO"]
for t in M["tables"]:   # a "previous_<table>_id" column points back at the same table (the version chain)
    n = t["name"]
    for c in t["cols"]:
        if re.fullmatch(r"previous_" + re.escape(n) + r"_id", c["name"]) and c["type"] == pk_type(n):
            fks.append((n, c["name"], n))
out.append("")
for n, col, link in fks:
    out += [f"ALTER TABLE [dbo].{q(n)} ADD CONSTRAINT {q(f'FK_{n}_{col}')} FOREIGN KEY ({q(col)}) REFERENCES [dbo].{q(link)} ({q(pk_col(link))});"]
out.append("GO\n")


def prop(value, table, col=None):
    s = (f"EXEC sys.sp_addextendedproperty @name=N'MS_Description', @value={lit(value)}, @level0type=N'SCHEMA', @level0name=N'dbo', "
         f"@level1type=N'TABLE', @level1name={lit(table)}")
    if col:
        s += f", @level2type=N'COLUMN', @level2name={lit(col)}"
    return s + ";"


stmts = []
for t in M["tables"]:
    n = t["name"]
    stmts.append(prop(f"[{t['priority']}] [{t['group']}] One row is: {t['what']} Why: {t['purpose']}"[:3900], n))
    for c in t["cols"]:
        tag = f"[{c['priority']}]" + (" [RESTRICTED]" if c.get("restricted") else "") + (" [NEW IN REVIEW]" if c.get("rev") == "NEW" else "")
        stmts.append(prop(f"{tag} {c['desc']} If the source does not send it: {c['fb']}"[:3900], n, c["name"]))
for i in range(0, len(stmts), 100):
    out += stmts[i:i + 100] + ["GO"]
out += ["", f"-- Report: {len(fks)} foreign keys created; {len(skipped)} links not created as keys:"]
for n, col, link, why in skipped:
    out.append(f"--   {n}.{col} -> {link} ({why})")
open(SQL_OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"saved {SQL_OUT}: {len(T)} tables, {len(fks)} foreign keys, {len(skipped)} links not made into keys")
for n, col, link, why in skipped[:12]:
    print(f"   not a key: {n}.{col} -> {link} ({why})")

# ---------------------------------------------------------------- ER diagrams (Mermaid) by stage
groups = []
for t in M["tables"]:
    if t["group"] not in groups:
        groups.append(t["group"])
doc = ["# Entity-relationship diagrams", "",
       "GENERATED by `tools/data_model/build_sql.py`. Open this file in VS Code and use the Markdown preview (Mermaid extension) or view it on GitHub.",
       "Lines are the links between tables (child on the many side). Only links between tables are drawn; each table has more columns than shown (see the data dictionary).", ""]
allrel = sorted({(c, p) for c, _, p in fks})


def block(names, title, edges_among=None):
    names = set(names)
    rel = [(c, p) for c, p in allrel if c in names and p in names]
    s = [f"## {title}", "", "```mermaid", "erDiagram"]
    for n in sorted(names):
        s.append(f"    {n} {{")
        for c in T[n]["cols"][:1]:
            s.append(f"        {c['type'].split('(')[0].lower()} {c['name']} PK")
        s.append("    }")
    for c, p in rel:
        s.append(f"    {p} ||--o{{ {c} : has")
    return s + ["```", ""]


doc += block(list(T), "Whole model (links only)")
for g in groups:
    names = [t["name"] for t in M["tables"] if t["group"] == g]
    related = set(names) | {p for c, p in allrel if c in names} | {c for c, p in allrel if p in names and g.startswith(("1", "2", "3", "4"))}
    doc += block(related, f"{g} ({len(names)} tables, with the tables they link to)")
open(ER_OUT, "w", encoding="utf-8").write("\n".join(doc))
print("saved", ER_OUT)

# ---------------------------------------------------------------- table catalog (readable list of every table by stage)
CAT_OUT = os.environ.get("KRISNNAI_CATALOG_OUT") or os.path.join(DOCS, "TABLE-CATALOG.md")
cat = ["# Table catalog", "", "GENERATED by `tools/data_model/build_sql.py`. One section per stage of the journey; the column-level detail is in the data dictionary.", ""]
for g in groups:
    ts = [t for t in M["tables"] if t["group"] == g]
    cat += [f"## {g}", "", "| Table | Priority | One row is | Columns | Links to |", "|---|---|---|---|---|"]
    for t in ts:
        links = sorted({c["link"] for c in t["cols"] if c.get("link")})
        cat.append(f"| `{t['name']}` | {t['priority']} | {t['what']} | {len(t['cols'])} | {', '.join(f'`{x}`' for x in links)} |")
    cat.append("")
open(CAT_OUT, "w", encoding="utf-8").write("\n".join(cat))
print("saved", CAT_OUT)

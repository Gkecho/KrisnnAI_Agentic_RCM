"""Generate the PostgreSQL schema (tables, keys, foreign keys, column comments) from build/model.json.

Output (default docs/data_model/): schema_postgres.sql. Override with KRISNNAI_PG_OUT.
Same model and the same key rules as build_sql.py (SQL Server); only the type names and syntax differ.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.normpath(os.path.join(HERE, "..", "..", "docs", "data_model"))
PG_OUT = os.environ.get("KRISNNAI_PG_OUT") or os.path.join(DOCS, "schema_postgres.sql")
M = json.load(open(os.path.join(HERE, "build", "model.json"), encoding="utf-8"))
T = {t["name"]: t for t in M["tables"]}

SIMPLE = {"BIT": "BOOLEAN", "TINYINT": "SMALLINT", "DATETIME2(0)": "TIMESTAMP(0)", "BINARY(32)": "BYTEA"}


def pg_type(t):
    if t in SIMPLE:
        return SIMPLE[t]
    return t.replace("NVARCHAR", "VARCHAR")      # VARCHAR(n), CHAR(n), DECIMAL(p,s), DATE, INT, BIGINT, SMALLINT, TIME(0) are the same


def q(name):
    return '"' + name + '"'


def lit(s):
    return "'" + str(s).replace("'", "''") + "'"


def pk_col(table):
    return T[table]["cols"][0]["name"]


def pk_type(table):
    return T[table]["cols"][0]["type"]


out = ["-- KrisnnAI canonical data model: PostgreSQL schema. GENERATED by tools/data_model/build_postgres.py, do not edit by hand.",
       f"-- {len(T)} tables, {sum(len(t['cols']) for t in T.values())} columns. Synthetic data only; no real PHI.",
       "-- Mandatory columns are NOT NULL; Important and Optional are nullable (each has a documented fallback).",
       "-- Every table and column carries its description as a COMMENT.", ""]
fks, skipped = [], []
for t in M["tables"]:
    n = t["name"]
    lines = []
    for c in t["cols"]:
        is_pk = c["name"] == pk_col(n)
        ident = " GENERATED BY DEFAULT AS IDENTITY" if is_pk else ""
        null = "NOT NULL" if (c["priority"] == "Mandatory" or is_pk) else "NULL"
        lines.append(f"    {q(c['name'])} {pg_type(c['type'])}{ident} {null}")
        if c.get("link"):
            if c["link"] not in T:
                skipped.append((n, c["name"], c["link"], "unknown table"))
            elif pk_type(c["link"]) != c["type"]:
                skipped.append((n, c["name"], c["link"], f"{c['type']} vs {pk_type(c['link'])}"))
            else:
                fks.append((n, c["name"], c["link"]))
    lines.append(f"    CONSTRAINT {q('pk_' + n)} PRIMARY KEY ({q(pk_col(n))})")
    out += [f"CREATE TABLE {q(n)} (", ",\n".join(lines), ");", ""]
for t in M["tables"]:
    n = t["name"]
    for c in t["cols"]:
        if re.fullmatch(r"previous_" + re.escape(n) + r"_id", c["name"]) and c["type"] == pk_type(n):
            fks.append((n, c["name"], n))
for n, col, link in fks:
    out.append(f"ALTER TABLE {q(n)} ADD CONSTRAINT {q(f'fk_{n}_{col}')} "
               f"FOREIGN KEY ({q(col)}) REFERENCES {q(link)} ({q(pk_col(link))});")
out.append("")
for t in M["tables"]:
    n = t["name"]
    out.append(f"COMMENT ON TABLE {q(n)} IS {lit(f'[{t['priority']}] [{t['group']}] One row is: {t['what']} Why: {t['purpose']}')};")
    for c in t["cols"]:
        tag = f"[{c['priority']}]" + (" [RESTRICTED]" if c.get("restricted") else "") + (" [NEW IN REVIEW]" if c.get("rev") == "NEW" else "")
        out.append(f"COMMENT ON COLUMN {q(n)}.{q(c['name'])} IS {lit(f'{tag} {c['desc']} If the source does not send it: {c['fb']}')};")
out += ["", f"-- Report: {len(fks)} foreign keys created; {len(skipped)} links not created as keys:"]
out += [f"--   {n}.{col} -> {link} ({why})" for n, col, link, why in skipped]
open(PG_OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"saved {PG_OUT}: {len(T)} tables, {len(fks)} foreign keys, {len(skipped)} links not made into keys")
